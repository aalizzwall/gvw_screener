import streamlit as st
import sqlite3
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import os

# Configuration
DB_PATH = "scoring_results.db"

def get_connection():
    return sqlite3.connect(DB_PATH)

def load_data(tickers=None):
    conn = get_connection()
    query = "SELECT ticker, score, timestamp FROM scoring_results"
    if tickers:
        placeholders = ', '.join(['?'] * len(tickers))
        query += f" WHERE ticker IN ({placeholders})"
    
    df = pd.read_sql_query(query, conn, params=tickers if tickers else None)
    conn.close()
    if not df.empty:
        df['timestamp'] = pd.to_datetime(df['timestamp'])
    return df

def main():
    st.set_page_config(page_title="GVW Screener Dashboard", layout="wide")
    st.title("📊 GVW Scoring Dashboard")

    if not os.path.exists(DB_PATH):
        st.error(f"Database not found at {DB_PATH}")
        return

    # Sidebar for filters
    st.sidebar.header("Filters")
    
    # Get available tickers
    conn = get_connection()
    tickers_df = pd.read_sql_query("SELECT DISTINCT ticker FROM scoring_results", conn)
    all_tickers = tickers_df['ticker'].tolist()
    conn.close()

    selected_tickers = st.sidebar.multiselect("Select Tickers", all_tickers, default=all_tickers[:3] if len(all_tickers) > 3 else all_tickers)

    # Load data
    df = load_data(selected_tickers)

    if df.empty:
        st.warning("No data available for the selected tickers.")
        return

    # Metrics Row
    st.subheader("Summary Metrics")
    cols = st.columns(len(selected_tickers) if len(selected_tickers) <= 4 else 4)
    
    for i, ticker in enumerate(selected_tickers[:4]):
        ticker_data = df[df['ticker'] == ticker]
        if not ticker_data.empty:
            latest_score = ticker_data.iloc[-1]['score']
            avg_score = ticker_data['score'].mean()
            
            with cols[i % 4]:
                st.metric(label=f"{ticker} Latest Score", value=f"{latest_score:.2f}", delta=f"{latest_score - ticker_data.iloc[-2]['score']:.2f}" if len(ticker_data) > 1 else None)
                st.write(f"Average: {avg_score:.2f}")

    # Historical Trends Chart
    st.subheader("Scoring Trends")
    fig = px.line(df, x="timestamp", y="score", color="ticker", title="Score Over Time")
    st.plotly_chart(fig, use_container_width=True)

    # Backtesting Section
    st.divider()
    st.subheader("Backtesting Results")
    # In a real implementation, we would look for backtest result files or tables.
    # For now, we provide a placeholder or check for common patterns.
    st.info("Backtesting results can be viewed here once generated by the engine.")
    
    # Example of how to display backtest data if it were in a table
    # st.dataframe(pd.read_sql_query("SELECT * FROM backtest_results", conn))

if __name__ == "__main__":
    main()
